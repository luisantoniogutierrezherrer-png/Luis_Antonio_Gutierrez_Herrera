# Programa para calcular el área de un rectángulo

# Solicitar base y altura
base = float(input("Introduce la base del rectángulo (en metros): "))
altura = float(input("Introduce la altura del rectángulo (en metros): "))

# Calcular el área
area = base * altura

# Mostrar el resultado
print(f"El área del rectángulo es: {area} metros cuadrados")